// Enrich each project with date and popularity metrics for flexible sorting
export const galleryProjects: ProjectItem[] = rawProjects.map((p, idx) => {
  // Generate realistic sequential dates from recently completed in 2026 backwards to 2024
  const daysAgo = idx * 6;
  const projectDate = new Date(2026, 8, 20); // Sept 20, 2026
  projectDate.setDate(projectDate.getDate() - daysAgo);
  const dateStr = projectDate.toISOString().split('T')[0];

  // Realistic popularity score: featured items get 90-99, others distributed from 65 to 89
  const basePopularity = p.featured ? 92 + (idx % 8) : 65 + ((idx * 7) % 25);

  return {
    ...p,
    date: dateStr,
    popularity: basePopularity,
  };
});

export const getCategorizedProjects = (category: GalleryCategoryId | 'all'): ProjectItem[] => {
  if (category === 'all') return galleryProjects;
  return galleryProjects.filter((p) => p.category === category);
};

